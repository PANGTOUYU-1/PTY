"""Build the recipe icon registry from local DST Chinese strings and supplied PNGs.

Usage: python tools/build_vanilla_icons.py --strings path/to/chinese_s.po
The four inventoryimages directories are kept unchanged. Recipe materials and used
crafting stations and moon-eye inserts with supplied icons are indexed.
"""
import argparse
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Existing Wiki wording, verified against the mod's ingredient prefab identifiers.
ALIASES = {
    "金色羽毛": "feather_canary", "草": "cutgrass", "活木": "livinglog",
    "伏特羊奶": "goatmilk", "鱼肉": "fishmeat",
}
MOON_EYES = (
    "redmooneye", "bluemooneye", "orangemooneye",
    "yellowmooneye", "greenmooneye", "purplemooneye",
)


def build(strings):
    names = {}
    for block in strings.split("\n\n"):
        context = re.search(r'^msgctxt "STRINGS\.NAMES\.([^\"]+)"$', block, re.M)
        translated = re.search(r'^msgstr (".*")$', block, re.M)
        if context and translated:
            names[context[1].lower()] = json.loads(translated[1])
    images = {}
    for folder in sorted((ROOT / "assets/img").glob("inventoryimages[1-4]")):
        for image in sorted(folder.glob("*.png")):
            if image.stem in images:
                raise ValueError(f"Duplicate icon: {image.stem}")
            images[image.stem] = image.relative_to(ROOT).as_posix()
    by_name = collections.defaultdict(list)
    for prefab, name in names.items():
        if prefab in images:
            by_name[name].append(prefab)
    data = json.loads((ROOT / "data/site-data.js").read_text("utf-8").split("window.SITE_DATA = ", 1)[1].rstrip().removesuffix(";"))
    registry = {}
    # Equipment inserts shown in the moon-eye effect table.
    for prefab in MOON_EYES:
        registry[prefab] = {"name": names[prefab], "image": images[prefab], "aliases": []}
    # Crafting stations are requirements, so they do not appear as name×quantity.
    for prefab in ("researchlab", "researchlab2", "cookpot"):
        if prefab not in names or prefab not in images:
            continue
        if any(names[prefab] in str(entry.get("tech", "")) + str(entry.get("recipe", ""))
               for group in data.values() if isinstance(group, list)
               for entry in group if isinstance(entry, dict)):
            registry[prefab] = {"name": names[prefab], "image": images[prefab], "aliases": []}
    for group in data.values():
        if not isinstance(group, list):
            continue
        for entry in group:
            if not isinstance(entry, dict):
                continue
            recipe = entry.get("recipe", "")
            for match in re.finditer(r"([^\s：；，+×\[\]]+)(?=×)", recipe):
                word = match[1].removeprefix("或")
                # Sanity is a character cost, not a physical material.
                if word == "理智":
                    continue
                candidates = by_name.get(word, [])
                prefab = ALIASES.get(word) or (candidates[0] if len(candidates) == 1 else None)
                if word == "岩浆虫卵":
                    prefab = "lavae_egg"  # Unhatched egg, not the cracked variant.
                if not prefab or prefab not in images:
                    raise ValueError(f"Unresolved recipe material: {word}")
                icon = registry.setdefault(prefab, {"name": names[prefab], "image": images[prefab], "aliases": []})
                if word != icon["name"] and word not in icon["aliases"]:
                    icon["aliases"].append(word)
    content = "/** Original DST item and crafting station icons; generated by tools/build_vanilla_icons.py. */\nwindow.VANILLA_ICONS = " + json.dumps(dict(sorted(registry.items())), ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "data/vanilla-icons.js").write_text(content, encoding="utf-8", newline="\n")
    print(f"Indexed {len(registry)} items and crafting stations from {len(images)} original icons.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--strings", type=Path, required=True)
    args = parser.parse_args()
    build(args.strings.read_text("utf-8"))
